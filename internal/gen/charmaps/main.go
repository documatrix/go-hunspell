// Command charmaps regenerates internal/charset/maps.go: the byte to Unicode
// tables of the 8-bit encodings Hunspell dictionaries may be written in.
//
// It is a separate module so that the gohunspell module itself has no
// dependencies. Run it from the root of the repository:
//
//	go -C internal/gen/charmaps run . -out ../../charset/maps.go
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"unicode/utf8"

	"golang.org/x/text/encoding"
	"golang.org/x/text/encoding/charmap"
)

// table is an encoding: its normalized name, the x/text codec and the bytes
// the codec maps that the standard leaves undefined.
type table struct {
	name      string
	enc       encoding.Encoding
	undefined func(b int) bool
	c1        bool // 0x80-0x9F are the C1 controls (ISO 8859, TIS-620)
}

// overrides are the bytes where x/text differs from the standard: its
// KOI8-U has the Belarusian letters of KOI8-RU, RFC 2319 box drawings.
var overrides = map[string]map[int]rune{
	"koi8u": {0xAE: 0x255D, 0xBE: 0x256C},
}

// thai marks the no-break space of Windows-874 undefined for TIS-620, which
// lacks it; ISO 8859-11 has it.
func thai(nbsp bool) func(b int) bool {
	return func(b int) bool { return b == 0xA0 && !nbsp }
}

var tables = []table{
	{"iso88591", charmap.ISO8859_1, nil, true},
	{"iso88592", charmap.ISO8859_2, nil, true},
	{"iso88593", charmap.ISO8859_3, nil, true},
	{"iso88594", charmap.ISO8859_4, nil, true},
	{"iso88595", charmap.ISO8859_5, nil, true},
	{"iso88596", charmap.ISO8859_6, nil, true},
	{"iso88597", charmap.ISO8859_7, nil, true},
	{"iso88598", charmap.ISO8859_8, nil, true},
	{"iso88599", charmap.ISO8859_9, nil, true},
	{"iso885910", charmap.ISO8859_10, nil, true},
	{"iso885911", charmap.Windows874, thai(true), true},
	{"iso885913", charmap.ISO8859_13, nil, true},
	{"iso885914", charmap.ISO8859_14, nil, true},
	{"iso885915", charmap.ISO8859_15, nil, true},
	{"iso885916", charmap.ISO8859_16, nil, true},
	{"koi8r", charmap.KOI8R, nil, false},
	{"koi8u", charmap.KOI8U, nil, false},
	{"cp1250", charmap.Windows1250, nil, false},
	{"cp1251", charmap.Windows1251, nil, false},
	{"cp1252", charmap.Windows1252, nil, false},
	{"tis620", charmap.Windows874, thai(false), true},
}

func main() {
	out := flag.String("out", "../../charset/maps.go", "output file")
	flag.Parse()
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/gen/charmaps. DO NOT EDIT.\n\n")
	b.WriteString("package charset\n\n")
	b.WriteString("// tables maps a normalised encoding name to the Unicode code point of each\n")
	b.WriteString("// byte value; 0xFFFF marks a byte the encoding leaves undefined.\n")
	b.WriteString("var tables = map[string]*[256]uint16{\n")
	for _, t := range tables {
		fmt.Fprintf(&b, "\t%q: {\n", t.name)
		dec := t.enc.NewDecoder()
		for i := 0; i < 256; i += 16 {
			b.WriteString("\t\t")
			for c := i; c < i+16; c++ {
				v := rune(0xFFFF)
				s, err := dec.Bytes([]byte{byte(c)})
				if t.c1 && c >= 0x80 && c <= 0x9F {
					v = rune(c) // the C1 controls of ISO 8859, which x/text leaves out
				} else if r, n := utf8.DecodeRune(s); err == nil && n == len(s) && r != utf8.RuneError && r <= 0xFFFF &&
					(t.undefined == nil || !t.undefined(c)) {
					v = r
				}
				if r, ok := overrides[t.name][c]; ok {
					v = r
				}
				fmt.Fprintf(&b, "0x%04x, ", v)
			}
			b.WriteString("\n")
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}
