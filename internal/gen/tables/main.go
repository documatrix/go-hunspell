// Command tables regenerates the character tables of the core package from
// the Hunspell C++ sources.
//
// Usage:
//
//	go run ./internal/gen/tables -src /path/to/hunspell/src/hunspell -out internal/core
//
// It reads utf_info.hxx (the Unicode case/letter table) and csutil.cxx (the
// 8-bit charset case tables) and writes utf_info.go and cs_tables.go. The
// 8-bit to Unicode mappings used for I/O conversion live in the charset
// package and are produced by the charmaps generator.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

func main() {
	src := flag.String("src", "", "hunspell src/hunspell directory")
	out := flag.String("out", "internal/core", "output directory")
	flag.Parse()
	if *src == "" {
		log.Fatal("missing -src")
	}
	genUTF(filepath.Join(*src, "utf_info.hxx"), filepath.Join(*out, "utf_info.go"))
	genCS(filepath.Join(*src, "csutil.cxx"), filepath.Join(*out, "cs_tables.go"))
}

const header = "// Code generated by internal/gen/tables from the Hunspell sources. DO NOT EDIT.\n\n"

func genUTF(in, out string) {
	data, err := os.ReadFile(in)
	if err != nil {
		log.Fatal(err)
	}
	text := string(data)
	idxStart := strings.Index(text, "utf_page_index[256] = {")
	if idxStart < 0 {
		log.Fatal("page index not found")
	}
	idxEnd := strings.Index(text[idxStart:], "};")
	idxText := text[idxStart+len("utf_page_index[256] = {") : idxStart+idxEnd]
	idxText = regexp.MustCompile(`/\*[^*]*\*/`).ReplaceAllString(idxText, "")
	var index []string
	for _, f := range strings.Split(idxText, ",") {
		f = strings.TrimSpace(f)
		if f != "" {
			index = append(index, f)
		}
	}
	if len(index) != 256 {
		log.Fatalf("page index has %d entries", len(index))
	}
	entry := regexp.MustCompile(`\{ (true|false) *, (0x[0-9A-Fa-f]{4}), (0x[0-9A-Fa-f]{4}) \}`)
	pagesStart := strings.Index(text, "utf_pages[")
	var buf bytes.Buffer
	buf.WriteString(header)
	buf.WriteString("package core\n\n")
	buf.WriteString("var utfPageIndex = [256]uint8{\n")
	for i, v := range index {
		buf.WriteString(v)
		buf.WriteString(",")
		if i%16 == 15 {
			buf.WriteString("\n")
		}
	}
	buf.WriteString("}\n\n")
	matches := entry.FindAllStringSubmatch(text[pagesStart:], -1)
	if len(matches)%256 != 0 {
		log.Fatalf("unexpected entry count %d", len(matches))
	}
	fmt.Fprintf(&buf, "var utfPages = [%d][256]unicodeInfo{\n", len(matches)/256)
	for p := 0; p < len(matches)/256; p++ {
		buf.WriteString("{\n")
		for i := 0; i < 256; i++ {
			m := matches[p*256+i]
			fmt.Fprintf(&buf, "{%s,%s,%s},", m[1], m[2], m[3])
			if i%8 == 7 {
				buf.WriteString("\n")
			}
		}
		buf.WriteString("},\n")
	}
	buf.WriteString("}\n")
	write(out, buf.Bytes())
}

func genCS(in, out string) {
	f, err := os.Open(in)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	start := regexp.MustCompile(`^const struct cs_info (\w+)\[\] = \{`)
	entry := regexp.MustCompile(`\{(0x[0-9a-fA-F]{2}), (0x[0-9a-fA-F]{2}), (0x[0-9a-fA-F]{2})\}`)
	type table struct {
		name    string
		entries [][3]string
	}
	var tables []table
	var cur *table
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if m := start.FindStringSubmatch(line); m != nil {
			tables = append(tables, table{name: m[1]})
			cur = &tables[len(tables)-1]
			continue
		}
		if cur == nil {
			continue
		}
		for _, m := range entry.FindAllStringSubmatch(line, -1) {
			cur.entries = append(cur.entries, [3]string{m[1], m[2], m[3]})
		}
		if strings.Contains(line, "};") {
			if len(cur.entries) != 256 {
				log.Fatalf("%s has %d entries", cur.name, len(cur.entries))
			}
			cur = nil
		}
	}
	var buf bytes.Buffer
	buf.WriteString(header)
	buf.WriteString("package core\n\n")
	for _, t := range tables {
		name := goName(t.name)
		fmt.Fprintf(&buf, "var %s = [256]csInfo{\n", name)
		for i, e := range t.entries {
			cc, _ := strconv.ParseUint(e[0], 0, 8)
			fmt.Fprintf(&buf, "{%d,%s,%s},", cc, e[1], e[2])
			if i%8 == 7 {
				buf.WriteString("\n")
			}
		}
		buf.WriteString("}\n\n")
	}
	write(out, buf.Bytes())
}

func goName(c string) string {
	c = strings.TrimSuffix(c, "_tbl")
	parts := strings.Split(c, "_")
	for i := range parts {
		parts[i] = strings.ToUpper(parts[i][:1]) + parts[i][1:]
	}
	return "cs" + strings.Join(parts, "")
}

func write(path string, src []byte) {
	formatted, err := format.Source(src)
	if err != nil {
		log.Fatalf("%s: %v", path, err)
	}
	if err := os.WriteFile(path, formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}
